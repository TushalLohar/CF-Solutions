const int MOD = 1e9 + 7;
const ll INF = 1e18;

void solve()
{
    ll n, k;
    cin >> n >> k;

    ll ans = min(n, k);
    ll remaining = n - ans;
    ll count = ans;

    ll cost = 2;

    while (count > 0 && remaining >= cost)
    {
        ll take = min(count, remaining / cost);

        ans += take;
        remaining -= take * cost;
        count = take; 
        cost *= 2;
    }

    cout << ans << "\n";
}

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t = 1;
    cin >> t;

    while (t--)
    {
        solve();
    }

    return 0;
}
